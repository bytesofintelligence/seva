-- ============================================================================
-- MIGRATION: 018_sponsorships.sql
-- Purpose: Sponsorship feature — charities post fundable "items" (e.g. "50
-- samosas"), volunteers pledge money/quantity toward them, charity confirms
-- receipt once the bank transfer lands. Adds bank details to charities so
-- volunteers know where to send money.
-- ============================================================================

-- ============================================================================
-- TABLE: sponsorship_items
-- ============================================================================
CREATE TABLE sponsorship_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  charity_id UUID NOT NULL REFERENCES charities(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  description TEXT,
  quantity_needed INT NOT NULL CHECK (quantity_needed > 0),
  unit_label TEXT NOT NULL DEFAULT 'items',
  total_cost NUMERIC(10,2) NOT NULL CHECK (total_cost > 0),
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'fully_pledged', 'fulfilled', 'closed')),
  category TEXT NOT NULL DEFAULT 'food', -- maps to design-system colour pairs, free text (no fixed enum yet)
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT sponsorship_items_period_check CHECK (period_end >= period_start)
);

-- ============================================================================
-- TABLE: pledges
-- ============================================================================
CREATE TABLE pledges (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id UUID NOT NULL REFERENCES sponsorship_items(id) ON DELETE CASCADE,
  volunteer_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  quantity INT NOT NULL CHECK (quantity > 0),
  amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  reference TEXT NOT NULL UNIQUE, -- generated by trigger below, e.g. 'SEVA-4F7K'
  status TEXT NOT NULL DEFAULT 'pledged'
    CHECK (status IN ('pledged', 'transfer_claimed', 'received', 'cancelled', 'expired')),
  gift_aid BOOLEAN NOT NULL DEFAULT FALSE,
  gift_aid_full_name TEXT,
  gift_aid_address TEXT,
  gift_aid_postcode TEXT,
  claimed_at TIMESTAMPTZ,
  received_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT pledges_gift_aid_fields_check CHECK (
    gift_aid = FALSE
    OR (gift_aid_full_name IS NOT NULL AND gift_aid_address IS NOT NULL AND gift_aid_postcode IS NOT NULL)
  )
);

-- ============================================================================
-- TRIGGER: auto-generate pledge reference on insert
-- Format: 'SEVA-' + 4 random unambiguous alphanumerics (no 0/O/1/I), e.g. 'SEVA-4F7K'
-- ============================================================================
CREATE OR REPLACE FUNCTION generate_pledge_reference()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'public'
AS $$
DECLARE
  chars TEXT := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  candidate TEXT;
  i INT;
  attempt INT := 0;
BEGIN
  IF NEW.reference IS NOT NULL THEN
    RETURN NEW;
  END IF;

  LOOP
    candidate := 'SEVA-';
    FOR i IN 1..4 LOOP
      candidate := candidate || substr(chars, floor(random() * length(chars))::int + 1, 1);
    END LOOP;

    EXIT WHEN NOT EXISTS (SELECT 1 FROM pledges WHERE reference = candidate);

    attempt := attempt + 1;
    IF attempt > 20 THEN
      RAISE EXCEPTION 'Could not generate a unique pledge reference after % attempts', attempt;
    END IF;
  END LOOP;

  NEW.reference := candidate;
  RETURN NEW;
END;
$$;

CREATE TRIGGER generate_pledge_reference_trigger
BEFORE INSERT ON pledges
FOR EACH ROW
EXECUTE FUNCTION generate_pledge_reference();

-- ============================================================================
-- TRIGGER: enforce pledge status transitions server-side
--
-- Rules (see SECURITY.md):
--   - Only `status` (and the derived claimed_at/received_at timestamps) may
--     ever change on a pledge row. Every other column is set at creation and
--     is immutable thereafter.
--   - The pledger may move pledged -> transfer_claimed or pledged -> cancelled.
--   - The charity owner may move transfer_claimed -> received or -> cancelled.
--   - pledged -> expired is allowed unconditionally (no role check) as long
--     as the pledge is actually >48h old — this is what lets the lazy expiry
--     RPC (expire_stale_pledges, below) run as a normal authenticated caller
--     without needing special-cased permissions, since the age check itself
--     is the only thing that can ever authorize that specific transition.
--
-- This is done in a trigger rather than relying solely on RLS USING/WITH
-- CHECK pairing, because Postgres combines multiple permissive policies with
-- OR independently on USING and WITH CHECK — it does not pair a specific
-- USING clause with its "matching" WITH CHECK clause, so encoding "old status
-- X + new status Y" pairs purely in policies is not reliable. A trigger sees
-- both OLD and NEW directly and is unambiguous.
-- ============================================================================
CREATE OR REPLACE FUNCTION enforce_pledge_status_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'public'
AS $$
DECLARE
  is_volunteer BOOLEAN := (OLD.volunteer_id = auth.uid());
  is_charity_owner BOOLEAN := EXISTS (
    SELECT 1 FROM sponsorship_items si
    JOIN charities c ON c.id = si.charity_id
    WHERE si.id = OLD.item_id AND c.owner_id = auth.uid()
  );
BEGIN
  IF NEW.item_id IS DISTINCT FROM OLD.item_id
    OR NEW.volunteer_id IS DISTINCT FROM OLD.volunteer_id
    OR NEW.quantity IS DISTINCT FROM OLD.quantity
    OR NEW.amount IS DISTINCT FROM OLD.amount
    OR NEW.reference IS DISTINCT FROM OLD.reference
    OR NEW.gift_aid IS DISTINCT FROM OLD.gift_aid
    OR NEW.gift_aid_full_name IS DISTINCT FROM OLD.gift_aid_full_name
    OR NEW.gift_aid_address IS DISTINCT FROM OLD.gift_aid_address
    OR NEW.gift_aid_postcode IS DISTINCT FROM OLD.gift_aid_postcode
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
  THEN
    RAISE EXCEPTION 'Only the status of a pledge may be updated';
  END IF;

  IF NEW.status = OLD.status THEN
    RETURN NEW;
  END IF;

  IF OLD.status = 'pledged' AND NEW.status = 'expired'
     AND OLD.created_at < NOW() - INTERVAL '48 hours' THEN
    RETURN NEW;
  END IF;

  IF is_volunteer AND OLD.status = 'pledged' AND NEW.status IN ('transfer_claimed', 'cancelled') THEN
    IF NEW.status = 'transfer_claimed' THEN
      NEW.claimed_at := NOW();
    END IF;
    RETURN NEW;
  END IF;

  IF is_charity_owner AND OLD.status = 'transfer_claimed' AND NEW.status IN ('received', 'cancelled') THEN
    IF NEW.status = 'received' THEN
      NEW.received_at := NOW();
    END IF;
    RETURN NEW;
  END IF;

  RAISE EXCEPTION 'Invalid pledge status transition from % to %', OLD.status, NEW.status;
END;
$$;

CREATE TRIGGER enforce_pledge_status_transition_trigger
BEFORE UPDATE ON pledges
FOR EACH ROW
EXECUTE FUNCTION enforce_pledge_status_transition();

-- ============================================================================
-- CHARITIES: bank details for receiving sponsorship transfers
--
-- NOTE (see SECURITY.md): the existing `charities_select` policy allows any
-- authenticated user to read every column of a charity row. RLS is row-level
-- only, so adding these as plain columns does NOT hide them from that policy.
-- We deliberately do not lock this down with column-level GRANT/REVOKE here,
-- because several existing screens already run `select('*')` on charities
-- (onboarding-profile-charity.tsx, charity-dashboard.tsx, charity/[id].tsx)
-- and that would break immediately. Instead, get_bank_details() below is the
-- intended read path for volunteers. This is a known gap — see SECURITY.md.
-- ============================================================================
ALTER TABLE charities ADD COLUMN IF NOT EXISTS bank_account_name TEXT;
ALTER TABLE charities ADD COLUMN IF NOT EXISTS bank_sort_code TEXT; -- formatted '00-00-00'
ALTER TABLE charities ADD COLUMN IF NOT EXISTS bank_account_number TEXT; -- 8 digits

-- ============================================================================
-- VIEW: sponsorship_item_progress
-- Single source of truth for remaining/pledged/received amounts — mirrors the
-- opportunity_volunteer_counts pattern. No counter columns on the base table.
-- ============================================================================
CREATE OR REPLACE VIEW sponsorship_item_progress AS
SELECT
  si.id AS item_id,
  si.charity_id,
  COALESCE(SUM(CASE WHEN p.status IN ('pledged', 'transfer_claimed', 'received') THEN p.quantity ELSE 0 END), 0)::BIGINT AS quantity_pledged,
  COALESCE(SUM(CASE WHEN p.status = 'received' THEN p.quantity ELSE 0 END), 0)::BIGINT AS quantity_received,
  COALESCE(SUM(CASE WHEN p.status IN ('pledged', 'transfer_claimed', 'received') THEN p.amount ELSE 0 END), 0)::NUMERIC(10,2) AS amount_pledged,
  COALESCE(SUM(CASE WHEN p.status = 'received' THEN p.amount ELSE 0 END), 0)::NUMERIC(10,2) AS amount_received,
  GREATEST(
    si.quantity_needed - COALESCE(SUM(CASE WHEN p.status IN ('pledged', 'transfer_claimed', 'received') THEN p.quantity ELSE 0 END), 0),
    0
  )::BIGINT AS quantity_remaining
FROM sponsorship_items si
LEFT JOIN pledges p ON p.item_id = si.id
GROUP BY si.id, si.charity_id, si.quantity_needed;

-- ============================================================================
-- EXPIRY: lazy expiry via RPC, not pg_cron
--
-- Choice: pg_cron is not guaranteed to be enabled on every Supabase project
-- (it's an extension that must be turned on per-project, and isn't available
-- at all on some hosting tiers), so a migration that assumes it exists can
-- fail to apply or silently do nothing. Lazy expiry has no such dependency —
-- it's plain SQL that works identically on every Supabase project/tier.
--
-- Contract: once the UI layer is built, any screen reading pledges/items
-- (item detail, progress view, "my pledges") must call
-- `select expire_stale_pledges();` before querying, so stale rows are folded
-- in first. This is a deliberate trade-off: a pledge can sit "expired in
-- fact, pledged in name" for as long as nothing queries it, which is fine
-- here since nothing time-sensitive (like capacity limits) depends on the
-- exact expiry instant.
-- ============================================================================
CREATE OR REPLACE FUNCTION expire_stale_pledges()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'public'
AS $$
BEGIN
  UPDATE pledges
  SET status = 'expired'
  WHERE status = 'pledged'
    AND created_at < NOW() - INTERVAL '48 hours';
END;
$$;

REVOKE EXECUTE ON FUNCTION expire_stale_pledges() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION expire_stale_pledges() TO authenticated;

-- ============================================================================
-- RPC: get_bank_details
-- Returns a charity's bank details only if the caller has an active
-- (pledged or transfer_claimed) pledge against that charity. This is the
-- intended read path for bank details — see the NOTE on the charities
-- columns above.
-- ============================================================================
CREATE OR REPLACE FUNCTION get_bank_details(p_charity_id UUID)
RETURNS TABLE (
  bank_account_name TEXT,
  bank_sort_code TEXT,
  bank_account_number TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = 'public'
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pledges p
    JOIN sponsorship_items si ON si.id = p.item_id
    WHERE si.charity_id = p_charity_id
      AND p.volunteer_id = auth.uid()
      AND p.status IN ('pledged', 'transfer_claimed')
  ) THEN
    RAISE EXCEPTION 'Not authorized to view bank details for this charity';
  END IF;

  RETURN QUERY
  SELECT c.bank_account_name, c.bank_sort_code, c.bank_account_number
  FROM charities c
  WHERE c.id = p_charity_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION get_bank_details(UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION get_bank_details(UUID) TO authenticated;

-- ============================================================================
-- ROW LEVEL SECURITY: sponsorship_items
-- ============================================================================
ALTER TABLE sponsorship_items ENABLE ROW LEVEL SECURITY;

CREATE POLICY sponsorship_items_select ON sponsorship_items
  FOR SELECT
  TO authenticated
  USING (
    status != 'closed'
    OR EXISTS (SELECT 1 FROM charities c WHERE c.id = charity_id AND c.owner_id = auth.uid())
  );

CREATE POLICY sponsorship_items_insert ON sponsorship_items
  FOR INSERT
  TO authenticated
  WITH CHECK (
    EXISTS (SELECT 1 FROM charities c WHERE c.id = charity_id AND c.owner_id = auth.uid())
  );

CREATE POLICY sponsorship_items_update ON sponsorship_items
  FOR UPDATE
  TO authenticated
  USING (
    EXISTS (SELECT 1 FROM charities c WHERE c.id = charity_id AND c.owner_id = auth.uid())
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM charities c WHERE c.id = charity_id AND c.owner_id = auth.uid())
  );

CREATE POLICY sponsorship_items_delete ON sponsorship_items
  FOR DELETE
  TO authenticated
  USING (
    EXISTS (SELECT 1 FROM charities c WHERE c.id = charity_id AND c.owner_id = auth.uid())
  );

-- ============================================================================
-- ROW LEVEL SECURITY: pledges
-- Transition legality is enforced by enforce_pledge_status_transition_trigger
-- above; these policies only gate *who* may touch a row at all.
-- ============================================================================
ALTER TABLE pledges ENABLE ROW LEVEL SECURITY;

CREATE POLICY pledges_select ON pledges
  FOR SELECT
  TO authenticated
  USING (
    volunteer_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM sponsorship_items si
      JOIN charities c ON c.id = si.charity_id
      WHERE si.id = item_id AND c.owner_id = auth.uid()
    )
  );

CREATE POLICY pledges_insert ON pledges
  FOR INSERT
  TO authenticated
  WITH CHECK (volunteer_id = auth.uid());

CREATE POLICY pledges_update ON pledges
  FOR UPDATE
  TO authenticated
  USING (
    volunteer_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM sponsorship_items si
      JOIN charities c ON c.id = si.charity_id
      WHERE si.id = item_id AND c.owner_id = auth.uid()
    )
  )
  WITH CHECK (
    volunteer_id = auth.uid()
    OR EXISTS (
      SELECT 1 FROM sponsorship_items si
      JOIN charities c ON c.id = si.charity_id
      WHERE si.id = item_id AND c.owner_id = auth.uid()
    )
  );
